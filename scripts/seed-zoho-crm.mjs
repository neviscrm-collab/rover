#!/usr/bin/env node
/**
 * ROVER — Zoho CRM Live Data Seeder
 * ─────────────────────────────────────────────────────────────────────────────
 * Populates Zoho CRM with realistic sample data:
 *   • 5 Accounts    (Travel Agencies / Studios)
 *   • 10 Contacts   (Traveler profiles)
 *   • 8 Experiences (Travel packages)
 *   • 12 Bookings   (Linking travelers ↔ experiences)
 *
 * Usage:
 *   node scripts/seed-zoho-crm.mjs <access_token>
 *
 * Get your token:
 *   1. Log in at localhost:3013/login → Continue with Zoho CRM
 *   2. DevTools (F12) → Application → Local Storage → rover_auth_token → Copy Value
 */

const ACCESS_TOKEN = process.argv[2];
const DC = "in";

if (!ACCESS_TOKEN) {
  console.error("❌  Usage: node scripts/seed-zoho-crm.mjs <access_token>");
  process.exit(1);
}

const BASE  = `https://www.zohoapis.${DC}/crm/v2`;
const HEADS = {
  Authorization: `Zoho-oauthtoken ${ACCESS_TOKEN}`,
  "Content-Type": "application/json",
};

async function post(module, records) {
  const res  = await fetch(`${BASE}/${module}`, {
    method:  "POST",
    headers: HEADS,
    body:    JSON.stringify({ data: records }),
  });
  const json = await res.json();
  return { status: res.status, ok: res.ok, json };
}

function log(label, result) {
  const ids = result.json?.data?.map(d => d.details?.id).filter(Boolean) ?? [];
  if (result.ok && ids.length) {
    console.log(`  ✅  ${label} (${ids.length} record${ids.length > 1 ? "s" : ""}) → ${ids[0]}…`);
  } else {
    const msg = JSON.stringify(result.json).slice(0, 300);
    console.warn(`  ⚠️   ${label} HTTP ${result.status}: ${msg}`);
  }
  return ids;
}

